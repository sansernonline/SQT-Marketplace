import { test } from "node:test"; import assert from "node:assert/strict";
import { isValidThaiId } from "../src/thaiId.js"; import { normalizeThaiMobile } from "../src/phone.js";
import { bahtText } from "../src/bahtText.js"; import { toBuddhistDate } from "../src/buddhist.js";
test("id valid plain", () => assert.equal(isValidThaiId("1103700207180"), true));
test("id valid dashed", () => assert.equal(isValidThaiId("1-1037-00207-18-0"), true));
test("id bad checksum", () => assert.equal(isValidThaiId("1103700207181"), false));
test("id bad length", () => assert.equal(isValidThaiId("123"), false));
test("id non-digit", () => assert.equal(isValidThaiId("11037002071a1"), false));
test("phone dashes", () => assert.equal(normalizeThaiMobile("081-234-5678"), "+66812345678"));
test("phone +66", () => assert.equal(normalizeThaiMobile("+66812345678"), "+66812345678"));
test("phone spaced 66", () => assert.equal(normalizeThaiMobile("66 91 234 5678"), "+66912345678"));
test("phone 06", () => assert.equal(normalizeThaiMobile("0612345678"), "+66612345678"));
test("phone landline", () => assert.throws(() => normalizeThaiMobile("021234567")));
test("phone short", () => assert.throws(() => normalizeThaiMobile("08123")));
test("baht 21", () => assert.equal(bahtText(21), "ยี่สิบเอ็ดบาทถ้วน"));
test("baht 1234.5", () => assert.equal(bahtText(1234.5), "หนึ่งพันสองร้อยสามสิบสี่บาทห้าสิบสตางค์"));
test("baht 0", () => assert.equal(bahtText(0), "ศูนย์บาทถ้วน"));
test("baht million", () => assert.equal(bahtText(1000000), "หนึ่งล้านบาทถ้วน"));
test("baht 0.25", () => assert.equal(bahtText(0.25), "ยี่สิบห้าสตางค์"));
test("baht 101", () => assert.equal(bahtText(101), "หนึ่งร้อยเอ็ดบาทถ้วน"));
test("baht 11", () => assert.equal(bahtText(11), "สิบเอ็ดบาทถ้วน"));
test("baht 2011021", () => assert.equal(bahtText(2011021), "สองล้านหนึ่งหมื่นหนึ่งพันยี่สิบเอ็ดบาทถ้วน"));
test("baht 11000000", () => assert.equal(bahtText(11000000), "สิบเอ็ดล้านบาทถ้วน"));
test("be date", () => assert.equal(toBuddhistDate("2026-10-19"), "19/10/2569"));
test("be leap", () => assert.equal(toBuddhistDate("2024-02-29"), "29/02/2567"));
test("be invalid", () => assert.throws(() => toBuddhistDate("2026-02-30")));
test("be junk", () => assert.throws(() => toBuddhistDate("19/10/2026")));
