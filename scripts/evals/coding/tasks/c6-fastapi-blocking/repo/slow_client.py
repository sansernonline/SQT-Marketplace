"""Warehouse stock client — vendor library.

Do not edit this file: it is copied from the vendor and replaced on every update.
The call is blocking (it waits on the network); here the wait is simulated with time.sleep.
"""
import time

CALL_SECONDS = 0.2

_STOCK = {"A001": 12, "A002": 0, "A003": 7, "B100": 40, "B200": 3}


class NotFound(Exception):
    pass


def get_stock(sku):
    """Return {"sku": ..., "qty": ...} for one product. Raises NotFound for an unknown sku."""
    time.sleep(CALL_SECONDS)
    if sku not in _STOCK:
        raise NotFound(sku)
    return {"sku": sku, "qty": _STOCK[sku]}
